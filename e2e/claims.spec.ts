test('the attack recovers state from the blocks you generated and predicts your next click', async ({
  page
}) => {
  test.setTimeout(300_000);
  await page.goto('.');
  await waitForGenerators(page);

  // Generate the "intercepted traffic" ourselves so we know exactly what the
  // attacker is entitled to see.
  await generateBtn(page, DUAL_EC).click();
  await expect(output(page, DUAL_EC)).not.toHaveText('—');
  const blockA = await text(output(page, DUAL_EC));
  await generateBtn(page, DUAL_EC).click();
  await expect.poll(async () => await text(output(page, DUAL_EC))).not.toBe(blockA);
  const blockB = await text(output(page, DUAL_EC));
  expect(blockB).not.toBe(blockA);

  await panel(page, DUAL_EC).locator('.btn-danger').click();
  const theater = page.locator('.attack-overlay');
  await expect(theater).toBeVisible();
  await expect(theater).toContainText('STATE RECOVERED', { timeout: 240_000 });

  // The attacker works from YOUR output — the two most recent blocks, verbatim.
  const overlay = (await theater.innerText()).replace(/ /g, ' ');
  expect(overlay.match(/block 1\s+([0-9a-f]+)/)?.[1]).toBe(blockA);
  expect(overlay.match(/block 2\s+([0-9a-f]+)/)?.[1]).toBe(blockB);
  // The prose's block size must be the block size actually on the wire.
  expect(overlay).toContain(`two consecutive ${blockB.length / 2}-byte output blocks`);
  expect(overlay).toContain(`Each output reveals ${(blockB.length / 2) * 8} of 256 bits`);

  // The search reports a real, bounded candidate count.
  const searched = overlay.match(/Searched ([\d,]+) candidates in /)?.[1];
  expect(searched, `progress label missing from: ${overlay}`).toBeTruthy();
  const candidates = Number.parseInt((searched ?? '').replace(/,/g, ''), 10);
  expect(candidates).toBeGreaterThan(0);
  expect(candidates).toBeLessThanOrEqual(65536);
  expect(overlay).toMatch(/STATE RECOVERED: s = 0x[0-9a-f]+/);

  // The bar and its accessible value must agree that the search is finished.
  const bar = theater.locator('[role="progressbar"]');
  await expect(bar).toHaveAttribute('aria-valuenow', '100');
  expect(await theater.locator('.progress-fill').evaluate((el) => el.style.width)).toBe('100%');

  // Ten predictions, verified one row at a time.
  await expect(theater.locator('.prediction-row')).toHaveCount(11, { timeout: 120_000 });
  const rows = (
    await theater
      .locator('.prediction-row')
      .evaluateAll((els) => els.map((el) => Array.from(el.children).map((c) => (c.textContent ?? '').trim())))
  ).filter((r) => r[0] !== 'PREDICTED');
  expect(rows).toHaveLength(10);
  for (const [predicted, actual, match] of rows) {
    expect(predicted).toMatch(/^[0-9a-f]{20}\.\.\.$/);
    // A ✅ must mean the two columns beside it are equal.
    expect(match === '✅').toBe(predicted === actual);
    expect(match).toBe('✅');
  }

  // The closing verdict is the tally of those rows, not a fixed headline. The
  // "YOUR MOVE" callout is written last, so waiting for it settles the panel.
  await expect(theater).toContainText('YOUR MOVE', { timeout: 60_000 });
  const summaryText = (await theater.innerText()).replace(/ /g, ' ');
  const tally = summaryText.match(/(TOTAL COMPROMISE|PARTIAL) — (\d+) of (\d+) predictions matched/);
  expect(tally, `no verdict found in: ${summaryText}`).not.toBeNull();
  const matched = Number(tally?.[2]);
  const total = Number(tally?.[3]);
  expect(total).toBe(rows.length);
  expect(matched).toBe(rows.filter((r) => r[2] === '✅').length);
  expect(tally?.[1] === 'TOTAL COMPROMISE').toBe(matched === total);
  expect(tally?.[1]).toBe('TOTAL COMPROMISE');

  // The body's arithmetic: N blocks at 240 bits each.
  const bits = summaryText.match(/From (\d+) intercepted output blocks — (\d+) bits/);
  expect(bits).not.toBeNull();
  expect(Number(bits?.[1])).toBe(2);
  expect(Number(bits?.[2])).toBe(Number(bits?.[1]) * 240);

  // The rate quoted in the summary is the rate the timing line measured, not a
  // constant standing in for one.
  const summaryRate = summaryText.match(/at ([\d,]+) candidates\/sec in this tab/)?.[1];
  const timingRate = summaryText.match(/· ([\d,]+) candidates\/sec in this browser tab/)?.[1];
  expect(summaryRate).toBeTruthy();
  expect(summaryRate).toBe(timingRate);

  /* --- and now the headline claim: it predicts your NEXT click --- */

  const predictedNext = summaryText.match(/next Generate click will output:\s*\n?\s*([0-9a-f]{60})/)?.[1];
  expect(predictedNext, `YOUR MOVE hex missing from: ${summaryText}`).toBeTruthy();
  await expect(predictBadge(page)).toBeVisible();
  await expect(predictBadge(page)).toContainText(
    `Attacker's prediction for your NEXT Generate: ${(predictedNext ?? '').slice(0, 24)}…`
  );
  // The armed prediction is the first verified row.
  expect(rows[0][0]).toBe(`${(predictedNext ?? '').slice(0, 20)}...`);

  const beforeClick = await text(output(page, DUAL_EC));
  expect(beforeClick).not.toBe(predictedNext);
  await generateBtn(page, DUAL_EC).click();
  await expect.poll(async () => await text(output(page, DUAL_EC))).not.toBe(beforeClick);

  // THE claim: the bytes the generator just produced are the bytes the attacker
  // wrote down before the click.
  expect(await text(output(page, DUAL_EC))).toBe(predictedNext);
  await expect(predictBadge(page)).toContainText(
    'The attacker predicted this exact output before you clicked'
  );
  const nextPredicted = (await text(predictBadge(page))).match(/Next predicted: ([0-9a-f]{24})…/)?.[1];
  expect(nextPredicted).toBeTruthy();
  expect(rows[1][0]).toBe(`${(nextPredicted ?? '').slice(0, 20)}...`);

  /* --- reseeding revokes the attacker's knowledge --- */

  await reseedBtn(page, DUAL_EC).click();
  await expect(stateLine(page, DUAL_EC)).toHaveText(/reseed_counter: 1 \(reseeded\)/);
  await expect(predictBadge(page)).toBeHidden();

  const afterReseed = await text(output(page, DUAL_EC));
  await generateBtn(page, DUAL_EC).click();
  await expect.poll(async () => await text(output(page, DUAL_EC))).not.toBe(afterReseed);
  // Fresh entropy means the queued prediction is worthless and is not claimed.
  await expect(predictBadge(page)).toBeHidden();
  expect(await text(output(page, DUAL_EC))).not.toContain(nextPredicted ?? 'unreachable');
});
